AA3_TO_1 = {
    "ALA": "A", "ARG": "R", "ASN": "N",
    "ASP": "D", "CYS": "C", "GLU": "E",
    "GLN": "Q", "GLY": "G", "HIS": "H",
    "ILE": "I", "LEU": "L", "LYS": "K",
    "MET": "M", "PHE": "F", "PRO": "P",
    "SER": "S", "THR": "T", "TRP": "W",
    "TYR": "Y", "VAL": "V", "MSE": "M"
}


def extract_pdb_chain_sequences(pdb_text):

    chain_data = {}

    seen_residues = set()

    for line in pdb_text.splitlines():

        record = line[0:6].strip()

        if record not in ("ATOM", "HETATM"):
            continue

        if len(line) < 27:
            continue

        atom_name = line[12:16].strip()

        if atom_name != "CA":
            continue

        altloc = line[16:17]

        if altloc not in (" ", "A"):
            continue

        resname = line[17:20].strip().upper()

        amino_acid = AA3_TO_1.get(resname)

        if amino_acid is None:
            continue

        chain = line[21:22].strip() or "_"
        residue_number = line[22:26].strip()
        insertion_code = line[26:27].strip()

        residue_key = (chain, residue_number, insertion_code)

        if residue_key in seen_residues:
            continue

        seen_residues.add(residue_key)

        if chain not in chain_data:
            chain_data[chain] = {
                "sequence": "",
                "residues": []
            }

        chain_data[chain]["sequence"] += amino_acid

        chain_data[chain]["residues"].append({
            "resname": resname,
            "amino_acid": amino_acid,
            "number": residue_number,
            "insertion_code": insertion_code,
            "chain": chain
        })

    return chain_data


def align_protein_sequences(query_sequence, pdb_sequence):

    n = len(pdb_sequence)
    m = len(query_sequence)

    if n == 0 or m == 0:
        return None

    # Smith-Waterman local alignment

    score = [
        [0] * (m + 1)
        for _ in range(n + 1)
    ]

    traceback = [
        [0] * (m + 1)
        for _ in range(n + 1)
    ]

    match_score = 2
    mismatch_score = -1
    gap_penalty = -2

    best_score = 0
    best_position = (0, 0)

    for i in range(1, n + 1):

        for j in range(1, m + 1):

            diagonal = score[i-1][j-1] + (
                match_score
                if pdb_sequence[i-1] == query_sequence[j-1]
                else mismatch_score
            )

            up = score[i-1][j] + gap_penalty

            left = score[i][j-1] + gap_penalty

            best = max(0, diagonal, up, left)

            score[i][j] = best

            if best == 0:
                traceback[i][j] = 0

            elif best == diagonal:
                traceback[i][j] = 1

            elif best == up:
                traceback[i][j] = 2

            else:
                traceback[i][j] = 3

            if best > best_score:

                best_score = best
                best_position = (i, j)

    # Traceback

    i, j = best_position

    residue_mapping = {}

    matches = 0
    aligned_pairs = 0

    while i > 0 and j > 0 and score[i][j] > 0:

        direction = traceback[i][j]

        if direction == 1:

            residue_mapping[j] = i - 1

            aligned_pairs += 1

            if pdb_sequence[i-1] == query_sequence[j-1]:
                matches += 1

            i -= 1
            j -= 1

        elif direction == 2:
            i -= 1

        elif direction == 3:
            j -= 1

        else:
            break

    if aligned_pairs == 0:
        return None

    identity = (matches / aligned_pairs) * 100

    coverage = (aligned_pairs / len(query_sequence)) * 100

    return {
        "mapping": residue_mapping,
        "score": best_score,
        "identity": identity,
        "coverage": coverage
    }




