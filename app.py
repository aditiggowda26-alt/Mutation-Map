def create_mutation_report_pdf(report_data, pdb_id="Not provided", chain_id="Not mapped", pdb_residue="Not mapped"):
    """Create a concise PDF report from saved MutationMap analysis results."""
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4, rightMargin=18*mm, leftMargin=18*mm,
        topMargin=16*mm, bottomMargin=16*mm
    )
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="SmallBody", parent=styles["BodyText"], fontSize=8, leading=11))
    story = [
        Paragraph("MutationMap – Mutation Analysis Report", styles["Title"]),
        Spacer(1, 5*mm),
        Paragraph("Computational analysis of an amino acid substitution", styles["Italic"]),
        Spacer(1, 5*mm),
        Paragraph("1. Mutation Details", styles["Heading2"]),
    ]
    details = [
        ["Protein sequence length", f"{report_data['length']} amino acids"],
        ["Mutation", report_data["mutation"]],
        ["Position", str(report_data["position"])],
        ["Mutation classification", report_data["mutation_type"]],
        ["PDB ID", pdb_id],
        ["PDB chain", str(chain_id)],
        ["PDB residue number", str(pdb_residue)],
    ]
    table = Table(details, colWidths=[55*mm, 105*mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (0,-1), colors.HexColor("#EAF0F6")),
        ("GRID", (0,0), (-1,-1), 0.4, colors.HexColor("#B8C2CC")),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("PADDING", (0,0), (-1,-1), 6),
    ]))
    story.extend([table, Spacer(1, 5*mm), Paragraph("2. Protein Property Comparison", styles["Heading2"])])
    rows = [["Property", "Wild type", "Mutant", "Change"]]
    for label, key, fmt in [
        ("Molecular weight (Da)", "molecular_weight", ".2f"),
        ("Isoelectric point (pI)", "isoelectric_point", ".2f"),
        ("GRAVY", "gravy", ".3f"),
        ("Instability index", "instability_index", ".2f"),
        ("Aliphatic index", "aliphatic_index", ".2f"),
        ("Aromaticity", "aromaticity", ".3f"),
        ("Net charge at pH 7", "charge", ".2f"),
    ]:
        a, b = report_data[key]
        rows.append([label, format(a, fmt), format(b, fmt), format(b-a, "+"+fmt)])
    prop_table = Table(rows, colWidths=[55*mm, 35*mm, 35*mm, 35*mm], repeatRows=1)
    prop_table.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#243B53")),
        ("TEXTCOLOR", (0,0), (-1,0), colors.white),
        ("GRID", (0,0), (-1,-1), 0.4, colors.HexColor("#B8C2CC")),
        ("ROWBACKGROUNDS", (0,1), (-1,-1), [colors.white, colors.HexColor("#F5F7FA")]),
        ("FONTSIZE", (0,0), (-1,-1), 8),
        ("PADDING", (0,0), (-1,-1), 5),
    ]))
    story.extend([prop_table, Spacer(1, 5*mm), Paragraph("3. Interpretation", styles["Heading2"])])
    for item in report_data["interpretation"]:
        story.append(Paragraph("• " + item, styles["SmallBody"]))
        story.append(Spacer(1, 1.5*mm))
    story.extend([
        Spacer(1, 3*mm),
        Paragraph("4. Sequences", styles["Heading2"]),
        Paragraph("Wild type: " + report_data["sequence"], styles["SmallBody"]),
        Spacer(1, 2*mm),
        Paragraph("Mutant: " + report_data["mutant"], styles["SmallBody"]),
        Spacer(1, 5*mm),
        Paragraph("Limitations", styles["Heading2"]),
        Paragraph("This report contains sequence-based computational estimates and PDB residue mapping information. These results do not independently establish experimentally confirmed changes in protein folding, stability, structure or biological function. The 3D viewer displays the supplied wild-type PDB structure; it does not generate a mutant 3D model.", styles["SmallBody"]),
        Spacer(1, 5*mm),
        Paragraph("Generated by MutationMap | Protein Engineering Capstone Project", styles["SmallBody"]),
    ])
    doc.build(story)
    return buffer.getvalue()




